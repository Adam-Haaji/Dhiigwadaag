// Scans frontend/assets/images and generates index.js with `images` and `imageList`
// Usage:
//   node ./scripts/generate-image-index.mjs        -> generates file
//   node ./scripts/generate-image-index.mjs --print -> also prints name + require code

import fs from 'fs';
import path from 'path';
import url from 'url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const imagesDir = path.join(projectRoot, 'assets', 'images');
const outFile = path.join(imagesDir, 'index.js');

const allowed = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif']);

function toKey(fileName) {
  // remove extension only
  return fileName.replace(/\.[^/.]+$/, '');
}

function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function main() {
  ensureDir(imagesDir);

  const entries = fs.readdirSync(imagesDir, { withFileTypes: true });
  const files = entries
    .filter((d) => d.isFile() && allowed.has(path.extname(d.name).toLowerCase()))
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));

  const lines = [];
  lines.push('// Auto-generated by scripts/generate-image-index.mjs. Do not edit by hand.');
  lines.push('');
  lines.push('export const images = {');
  for (const f of files) {
    const key = toKey(f);
    lines.push(`  "${key}": require("./${f}"),`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export const imageList = Object.entries(images).map(([name, source]) => ({ name, source }));');
  lines.push('');

  fs.writeFileSync(outFile, lines.join('\n'), 'utf8');

  const shouldPrint = process.argv.includes('--print');
  const header = `Generated ${path.relative(projectRoot, outFile)} with ${files.length} images.`;
  console.log(header);
  if (shouldPrint) {
    for (const f of files) {
      const name = toKey(f);
      console.log(`${name} -> require('./${f}')`);
    }
  }
}

main();
