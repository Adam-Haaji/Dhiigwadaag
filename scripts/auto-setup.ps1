<#
Automated setup for AI Blood Donation Matching & Emergency Alert System (Windows PowerShell)
- Creates/updates backend/.env with required variables
- Ensures Python venv, installs AI deps, trains model
- Starts FastAPI (port 8000), Node backend (port from .env), and Expo frontend (with EXPO_PUBLIC_API_BASE_URL)
#>

param(
  [string]$DatasetPath = "",
  [switch]$SkipFrontend
)

$ErrorActionPreference = 'Stop'

function Write-Section($msg) { Write-Host "`n=== $msg ===" -ForegroundColor Cyan }
function Require-Command($name) {
  if (-not (Get-Command $name -ErrorAction SilentlyContinue)) {
    throw "Required command '$name' not found in PATH"
  }
}

# 1) Ensure Node & Python exist
Write-Section "Checking prerequisites"
Require-Command node
Require-Command npm
Require-Command python

# 2) Create/Update backend/.env
Write-Section "Preparing backend/.env"
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$backendEnvPath = Join-Path (Join-Path $repoRoot 'backend') '.env'

# Preserve existing .env values (especially MONGO_URI) and only add missing defaults
$kv = [ordered]@{}
if (Test-Path $backendEnvPath) {
  Get-Content $backendEnvPath | ForEach-Object {
    if ($_ -match '^[\s#]') { return }
    if ($_ -match '^(?<k>[^=]+)=(?<v>.*)$') {
      $k = $Matches['k'].Trim(); $v = $Matches['v']
      if ($k) { $kv[$k] = $v }
    }
  }
}
function Set-IfMissing([string]$k,[string]$v) { if (-not $kv.Contains($k)) { $kv[$k] = $v } }

Set-IfMissing 'BACKEND_PORT' '5000'
# Do NOT override MONGO_URI if present; if missing and an Env var exists, use it; otherwise skip
if (-not $kv.Contains('MONGO_URI') -and $env:MONGO_URI) { $kv['MONGO_URI'] = $env:MONGO_URI }
Set-IfMissing 'MONGO_DB_NAME' 'blood-donation'
Set-IfMissing 'JWT_SECRET' 'your_secret_key'
Set-IfMissing 'FLASK_API_URL' 'http://localhost:5001'
Set-IfMissing 'AI_API_URL' 'http://127.0.0.1:8001/predict'
Set-IfMissing 'AI_MATCH_ALERT_THRESHOLD' '0.85'
Set-IfMissing 'FRONTEND_URL' 'http://localhost:8081'

# Write back
"# Auto-generated by auto-setup.ps1 (existing keys preserved)" | Out-File -FilePath $backendEnvPath -Encoding utf8 -Force
foreach ($k in $kv.Keys) { "$k=$($kv[$k])" | Add-Content -Path $backendEnvPath -Encoding utf8 }
Write-Host "Ensured $backendEnvPath with preserved MONGO_URI"

# Load env file into current session (simple parse of key=value)
(Get-Content $backendEnvPath) | ForEach-Object {
  if ($_ -match '^(?<k>[^#][^=]+)=(?<v>.*)$') {
    $k = $Matches['k'].Trim()
    $v = $Matches['v']
    Set-Item -Path ("Env:" + $k) -Value $v
  }
}

$aiServiceDir = Join-Path $repoRoot 'backend/ai-service'
$venvPy = Join-Path $aiServiceDir '.venv/Scripts/python.exe'

# 3) Ensure dataset exists or copy from provided path
Write-Section "Ensuring dataset exists"
$defaultCsv = Join-Path $aiServiceDir 'data/blood_donor_dataset.csv'
if (-not (Test-Path $defaultCsv)) {
  if ([string]::IsNullOrWhiteSpace($DatasetPath)) {
    # Try common fallback locations
    $candidates = @(
      (Join-Path $repoRoot 'blood_donor_dataset.csv'),
      (Join-Path $repoRoot 'backend/blood_donor_dataset.csv')
    )
    $found = $false
    foreach ($c in $candidates) {
      if (Test-Path $c) { Copy-Item $c $defaultCsv -Force; $found = $true; break }
    }
    if (-not $found) {
      throw "Dataset not found. Place it at $defaultCsv or pass -DatasetPath C:\\path\\to\\blood_donor_dataset.csv"
    }
  } else {
    if (-not (Test-Path $DatasetPath)) { throw "Provided -DatasetPath not found: $DatasetPath" }
    New-Item -ItemType Directory -Force -Path (Split-Path $defaultCsv) | Out-Null
    Copy-Item $DatasetPath $defaultCsv -Force
  }
}
Write-Host "Dataset ready at $defaultCsv"

# 4) Python venv + deps + train model
Write-Section "Setting up Python venv and training model"
Push-Location $aiServiceDir
if (-not (Test-Path (Join-Path $aiServiceDir '.venv'))) {
  python -m venv .venv
}
& $venvPy -m pip install --upgrade pip
& $venvPy -m pip install -r requirements.txt
& $venvPy blood_match_model.py
Pop-Location

# 5) Start FastAPI, Backend, and Frontend
Write-Section "Starting services"
# Start FastAPI
$fastapiCmd = "$venvPy -m uvicorn ai_model_api:app --reload --port 8001"
Start-Process powershell -ArgumentList "-NoExit","-Command","cd `"$aiServiceDir`"; $fastapiCmd" | Out-Null
Write-Host "Launched FastAPI on http://127.0.0.1:8001"

# Backend deps + run
$backendDir = Join-Path $repoRoot 'backend'
Start-Process powershell -ArgumentList "-NoExit","-Command","cd `"$backendDir`"; npm install; npm run dev" | Out-Null
Write-Host "Launched Backend on http://localhost:$($env:BACKEND_PORT)"

if (-not $SkipFrontend) {
  # Frontend deps + run with EXPO_PUBLIC_API_BASE_URL env
  $frontendDir = Join-Path $repoRoot 'frontend'
  $apiBase = "http://localhost:$($env:BACKEND_PORT)"
  $expoCmd = "$env:EXPO_PUBLIC_API_BASE_URL='$apiBase'; npm run start"
  Start-Process powershell -ArgumentList "-NoExit","-Command","cd `"$frontendDir`"; npm install; $expoCmd" | Out-Null
  Write-Host "Launched Frontend (Expo); API base: $apiBase"
}

Write-Section "All services started"
Write-Host "- FastAPI:  http://127.0.0.1:8001/health"
Write-Host "- Backend:  http://localhost:$($env:BACKEND_PORT)/api/health"
Write-Host "- Frontend: Use Expo to open the app (defaults to your device/simulator)."
